#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
生成 wiki_data.js —— 扫描 LLMWiki 目录，将所有 .md 文件打包为 JS 数据文件
供 WikiBrowser.html 直接加载（<script src> 不受浏览器 CORS 限制）
"""

import os
import json
import sys
from datetime import datetime


def escape_js_string(s):
    """转义字符串中的特殊字符，用于生成 JavaScript 字符串"""
    return s.replace('\\', '\\\\').replace("'", "\\'").replace('"', '\\"').replace('\n', '\\n').replace('\r', '\\r').replace('\t', '\\t')


def generate():
    # tools/ 的父目录是 Vicoding管理平台/，LLMWiki 在其下
    script_dir = os.path.dirname(os.path.abspath(__file__))
    wiki_root = os.path.join(script_dir, '..', 'LLMWiki')
    wiki_root = os.path.normpath(wiki_root)

    if not os.path.isdir(wiki_root):
        print(f"错误: 未找到 LLMWiki 目录: {wiki_root}")
        print("请确保本脚本放在 tools/ 目录下，且同级父目录存在 LLMWiki/")
        sys.exit(1)

    files = []
    for dirpath, dirnames, filenames in os.walk(wiki_root):
        for fname in filenames:
            if fname.endswith('.md'):
                full_path = os.path.join(dirpath, fname)
                rel_path = os.path.relpath(full_path, wiki_root).replace('\\', '/')
                name = os.path.splitext(fname)[0]
                try:
                    with open(full_path, 'r', encoding='utf-8') as f:
                        content = f.read()
                    stat = os.stat(full_path)
                    modified = datetime.fromtimestamp(stat.st_mtime).strftime('%Y-%m-%d %H:%M:%S')
                    files.append({
                        'path': rel_path,
                        'name': name,
                        'content': content,
                        'size': stat.st_size,
                        'modified': modified
                    })
                except Exception as e:
                    print(f"  警告: 读取失败 {rel_path}: {e}")

    # 按路径排序
    files.sort(key=lambda x: x['path'])

    # 生成 JS 文件
    output_path = os.path.join(script_dir, 'wiki_data.js')
    generated_at = datetime.now().strftime('%Y-%m-%d %H:%M:%S')

    with open(output_path, 'w', encoding='utf-8') as f:
        f.write('// Auto-generated by generate_wiki_data.py\n')
        f.write('// Do not edit manually. Run generate_wiki_data.py to regenerate.\n')
        f.write('window.WIKI_DATA = {\n')
        f.write("  wikiRoot: 'LLMWiki',\n")
        f.write(f"  generatedAt: '{generated_at}',\n")
        f.write(f"  totalFiles: {len(files)},\n")
        f.write("  files: [\n")

        for i, wf in enumerate(files):
            comma = ',' if i < len(files) - 1 else ''
            f.write("    {\n")
            f.write(f"      path: '{escape_js_string(wf['path'])}',\n")
            f.write(f"      name: '{escape_js_string(wf['name'])}',\n")
            f.write(f"      size: {wf['size']},\n")
            f.write(f"      modified: '{escape_js_string(wf['modified'])}',\n")
            # 内容可能很长，放在最后一行
            f.write(f"      content: '{escape_js_string(wf['content'])}'\n")
            f.write("    }" + comma + "\n")

        f.write("  ]\n")
        f.write("};\n")

    # 生成轻量元数据文件，供浏览器轮询检测更新
    meta_path = os.path.join(script_dir, 'wiki_data.meta.json')
    with open(meta_path, 'w', encoding='utf-8') as f:
        json.dump({
            'generatedAt': generated_at,
            'totalFiles': len(files),
            'wikiRoot': 'LLMWiki'
        }, f, ensure_ascii=False, indent=2)

    print(f"成功: 已生成 {output_path}")
    print(f"成功: 已生成 {meta_path}")
    print(f"  共 {len(files)} 个 Markdown 文件")
    total_size = sum(f['size'] for f in files)
    print(f"  总大小: {total_size / 1024:.1f} KB")


if __name__ == '__main__':
    generate()
